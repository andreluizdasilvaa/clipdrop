function showToast(message, type = 'info') {
  const container = document.getElementById('toastContainer');
  if (!container) return;

  const icon = type === 'success' ? ICONS.check : type === 'error' ? ICONS.alert : ICONS.info;
  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.setAttribute('role', type === 'error' ? 'alert' : 'status');
  toast.innerHTML = `<span class="toast-icon">${icon}</span><span class="toast-text">${escapeHtml(message)}</span>`;
  container.appendChild(toast);

  setTimeout(() => {
    toast.classList.add('toast-fade-out');
    setTimeout(() => toast.remove(), 400);
  }, 4500);
}

function isHttpUrl(text) {
  try {
    const url = new URL(text);
    return url.protocol === 'http:' || url.protocol === 'https:';
  } catch (_) {
    return false;
  }
}

/** HTML de um controle segmentado (ex.: MP3 | FLAC). */
function segmentedHtml(path, options, current) {
  const buttons = options.map((opt) => `
    <button type="button" class="seg-btn ${opt.value === current ? 'active' : ''}"
            data-seg="${escapeHtml(path)}" data-value="${escapeHtml(opt.value)}"
            aria-pressed="${opt.value === current}">${escapeHtml(opt.label)}</button>`).join('');
  return `<div class="segmented" role="group">${buttons}</div>`;
}

/** HTML de um toggle com rótulo. */
function toggleHtml(path, label, checked, hint = '') {
  return `
    <label class="toggle-row">
      <span class="toggle-text">
        <span class="toggle-label">${escapeHtml(label)}</span>
        ${hint ? `<span class="toggle-hint">${escapeHtml(hint)}</span>` : ''}
      </span>
      <span class="switch">
        <input type="checkbox" data-toggle="${escapeHtml(path)}" ${checked ? 'checked' : ''}>
        <span class="switch-track"></span>
      </span>
    </label>`;
}

